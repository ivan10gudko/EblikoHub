
DO
$$
BEGIN
    IF
NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'title_ratings'
          AND column_name = 'id'
    ) THEN
ALTER TABLE public.title_ratings
    ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;
END IF;

    IF
NOT EXISTS (
        SELECT 1 FROM information_schema.table_constraints tc
        JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name
        WHERE tc.table_schema = 'public'
          AND tc.table_name = 'title_ratings'
          AND tc.constraint_type = 'PRIMARY KEY'
    ) THEN
ALTER TABLE public.title_ratings
    ADD PRIMARY KEY (id);
END IF;
END $$;

ALTER TABLE public.title_ratings
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NULL,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NULL;

UPDATE public.title_ratings tr
SET created_at = COALESCE(t.created_at, CURRENT_TIMESTAMP),
    updated_at = COALESCE(t.created_at, CURRENT_TIMESTAMP) FROM public.titles t
WHERE tr.title_id = t.title_id AND tr.created_at IS NULL;

UPDATE public.title_ratings
SET created_at = CURRENT_TIMESTAMP,
    updated_at = CURRENT_TIMESTAMP
WHERE created_at IS NULL;

ALTER TABLE public.title_ratings
    ALTER COLUMN created_at SET NOT NULL;


